-- 01 Foundation: database, schemas, roles, warehouses
USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS FRAUD_AUTOML_DEMO
  DATA_RETENTION_TIME_IN_DAYS = 7
  COMMENT = 'Westpac demo: autonomous MLOps agent for fraud model';

CREATE SCHEMA IF NOT EXISTS FRAUD_AUTOML_DEMO.RAW        COMMENT = 'Landed source data';
CREATE SCHEMA IF NOT EXISTS FRAUD_AUTOML_DEMO.FEATURES   COMMENT = 'Feature Store and feature pipelines';
CREATE SCHEMA IF NOT EXISTS FRAUD_AUTOML_DEMO.ML         COMMENT = 'Model Registry, model monitors, training datasets';
CREATE SCHEMA IF NOT EXISTS FRAUD_AUTOML_DEMO.SERVING    COMMENT = 'Predictions and scoring';
CREATE SCHEMA IF NOT EXISTS FRAUD_AUTOML_DEMO.MONITORING COMMENT = 'DMFs, anomaly views, agent investigation tools, incidents';
CREATE SCHEMA IF NOT EXISTS FRAUD_AUTOML_DEMO.OPS        COMMENT = 'Git repo, generators, deploy procedures';

CREATE WAREHOUSE IF NOT EXISTS FRAUD_WH       WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS FRAUD_TRAIN_WH WAREHOUSE_SIZE = MEDIUM AUTO_SUSPEND = 60 INITIALLY_SUSPENDED = TRUE;

CREATE ROLE IF NOT EXISTS FRAUD_DE       COMMENT = 'Data engineering: RAW, FEATURES';
CREATE ROLE IF NOT EXISTS FRAUD_MLE      COMMENT = 'ML engineering: ML, SERVING';
CREATE ROLE IF NOT EXISTS FRAUD_AGENT_RO COMMENT = 'Autonomous agent: read-only across demo';
GRANT ROLE FRAUD_DE TO ROLE SYSADMIN;
GRANT ROLE FRAUD_MLE TO ROLE SYSADMIN;
GRANT ROLE FRAUD_AGENT_RO TO ROLE SYSADMIN;

GRANT USAGE ON DATABASE FRAUD_AUTOML_DEMO TO ROLE FRAUD_DE;
GRANT USAGE ON DATABASE FRAUD_AUTOML_DEMO TO ROLE FRAUD_MLE;
GRANT USAGE ON DATABASE FRAUD_AUTOML_DEMO TO ROLE FRAUD_AGENT_RO;
GRANT USAGE ON WAREHOUSE FRAUD_WH TO ROLE FRAUD_DE;
GRANT USAGE ON WAREHOUSE FRAUD_WH TO ROLE FRAUD_MLE;
GRANT USAGE ON WAREHOUSE FRAUD_WH TO ROLE FRAUD_AGENT_RO;
GRANT USAGE ON WAREHOUSE FRAUD_TRAIN_WH TO ROLE FRAUD_MLE;

GRANT ALL ON SCHEMA FRAUD_AUTOML_DEMO.RAW      TO ROLE FRAUD_DE;
GRANT ALL ON SCHEMA FRAUD_AUTOML_DEMO.FEATURES TO ROLE FRAUD_DE;
GRANT ALL ON SCHEMA FRAUD_AUTOML_DEMO.ML       TO ROLE FRAUD_MLE;
GRANT ALL ON SCHEMA FRAUD_AUTOML_DEMO.SERVING  TO ROLE FRAUD_MLE;
GRANT USAGE ON SCHEMA FRAUD_AUTOML_DEMO.FEATURES TO ROLE FRAUD_MLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA FRAUD_AUTOML_DEMO.FEATURES TO ROLE FRAUD_MLE;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA FRAUD_AUTOML_DEMO.FEATURES TO ROLE FRAUD_MLE;

-- Agent: read-only everywhere
GRANT USAGE ON ALL SCHEMAS IN DATABASE FRAUD_AUTOML_DEMO TO ROLE FRAUD_AGENT_RO;
GRANT SELECT ON FUTURE TABLES IN DATABASE FRAUD_AUTOML_DEMO TO ROLE FRAUD_AGENT_RO;
GRANT SELECT ON FUTURE VIEWS IN DATABASE FRAUD_AUTOML_DEMO TO ROLE FRAUD_AGENT_RO;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN DATABASE FRAUD_AUTOML_DEMO TO ROLE FRAUD_AGENT_RO;
GRANT USAGE ON FUTURE FUNCTIONS IN DATABASE FRAUD_AUTOML_DEMO TO ROLE FRAUD_AGENT_RO;
GRANT USAGE ON FUTURE MODELS IN DATABASE FRAUD_AUTOML_DEMO TO ROLE FRAUD_AGENT_RO;
GRANT DATABASE ROLE SNOWFLAKE.DATA_METRIC_USER TO ROLE FRAUD_AGENT_RO;
