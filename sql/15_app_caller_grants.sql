-- 15 Caller grants for the Mission Control app (owner role ACCOUNTADMIN).
-- Caller's-rights requests (run agent, approve/reject, verdict, Explore) are limited
-- to what the owner role may do on the caller's behalf.
USE ROLE ACCOUNTADMIN;

GRANT CALLER USAGE ON WAREHOUSE FRAUD_WH TO ROLE ACCOUNTADMIN;
GRANT CALLER USAGE ON DATABASE MLOPS_CONTROL TO ROLE ACCOUNTADMIN;
GRANT INHERITED CALLER USAGE ON ALL SCHEMAS IN DATABASE MLOPS_CONTROL TO ROLE ACCOUNTADMIN;
GRANT INHERITED CALLER SELECT ON ALL TABLES IN DATABASE MLOPS_CONTROL TO ROLE ACCOUNTADMIN;
GRANT INHERITED CALLER SELECT ON ALL VIEWS IN DATABASE MLOPS_CONTROL TO ROLE ACCOUNTADMIN;
GRANT INHERITED CALLER USAGE ON ALL PROCEDURES IN DATABASE MLOPS_CONTROL TO ROLE ACCOUNTADMIN;
GRANT CALLER INSERT ON TABLE MLOPS_CONTROL.CORE.ACTION_LOG TO ROLE ACCOUNTADMIN;
-- RUN_AGENT executes the agent's task as the caller (the task lives in the personal database)
GRANT CALLER USAGE ON DATABASE USER$ANUDEEP TO ROLE ACCOUNTADMIN;
GRANT CALLER USAGE ON SCHEMA USER$ANUDEEP.PUBLIC TO ROLE ACCOUNTADMIN;
GRANT CALLER OPERATE ON TASK USER$ANUDEEP.PUBLIC.COCO_ROUTINE_FRAUD_WATCH TO ROLE ACCOUNTADMIN;
-- Explore reads the systems' own data
GRANT CALLER USAGE ON DATABASE FRAUD_AUTOML_DEMO TO ROLE ACCOUNTADMIN;
GRANT INHERITED CALLER USAGE ON ALL SCHEMAS IN DATABASE FRAUD_AUTOML_DEMO TO ROLE ACCOUNTADMIN;
GRANT INHERITED CALLER SELECT ON ALL TABLES IN DATABASE FRAUD_AUTOML_DEMO TO ROLE ACCOUNTADMIN;
GRANT INHERITED CALLER SELECT ON ALL VIEWS IN DATABASE FRAUD_AUTOML_DEMO TO ROLE ACCOUNTADMIN;

-- Let approvers open the app
GRANT USAGE ON DATABASE MLOPS_CONTROL TO ROLE MLOPS_UI_RO;
GRANT USAGE ON SCHEMA MLOPS_CONTROL.APPS TO ROLE MLOPS_UI_RO;
GRANT USAGE ON APPLICATION SERVICE MLOPS_CONTROL.APPS.MISSION_CONTROL TO ROLE MLOPS_UI_RO;
